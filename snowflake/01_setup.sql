USE ROLE ACCOUNTADMIN;

-- Compute: the smallest size, switches itself off after 60 idle seconds
CREATE WAREHOUSE IF NOT EXISTS FIN_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;

-- A hard spending limit: suspend the warehouse if it ever burns 20 credits in a month
CREATE OR REPLACE RESOURCE MONITOR FIN_LIMIT
  WITH CREDIT_QUOTA = 20 FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE FIN_WH SET RESOURCE_MONITOR = FIN_LIMIT;

-- The pipeline's own role, and a database it owns
CREATE ROLE IF NOT EXISTS FIN_PIPELINE;
GRANT USAGE, OPERATE ON WAREHOUSE FIN_WH TO ROLE FIN_PIPELINE;
CREATE DATABASE IF NOT EXISTS FIN;
GRANT OWNERSHIP ON DATABASE FIN TO ROLE FIN_PIPELINE;
GRANT ROLE FIN_PIPELINE TO ROLE SYSADMIN;
SET me = '"' || CURRENT_USER() || '"';
GRANT ROLE FIN_PIPELINE TO USER IDENTIFIER($me);

-- A service user: a login for programs, not people. It cannot use a password at all.
CREATE USER IF NOT EXISTS FIN_SVC
  TYPE = SERVICE DEFAULT_ROLE = FIN_PIPELINE DEFAULT_WAREHOUSE = FIN_WH;
GRANT ROLE FIN_PIPELINE TO USER FIN_SVC;

-- Everything below is created by the pipeline role, so the role owns it
USE ROLE FIN_PIPELINE;
USE WAREHOUSE FIN_WH;
CREATE SCHEMA IF NOT EXISTS FIN.RAW;

-- A stage is a file drop-off area inside Snowflake
CREATE STAGE IF NOT EXISTS FIN.RAW.LANDING;

SHOW STAGES IN SCHEMA FIN.RAW;